package com.example.btgk;

public class Video {
    private String title;
    private String url;

    // Constructor
    public Video(String title, String url) {
        this.title = title;
        this.url = url;
    }

    // Getter and Setter
    public String getTitle() {
        return title;
    }

    public String getUrl() {
        return url;
    }
}
